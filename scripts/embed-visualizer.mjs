import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const source = readFileSync(resolve(root, 'visualizer/index.html'), 'utf8');
const output = `// Generated by scripts/embed-visualizer.mjs; edit visualizer/index.html instead.\nexport const visualizerHtml = ${JSON.stringify(source)};\n`;
writeFileSync(resolve(root, 'lib/visualizer-html.ts'), output);
console.log('Embedded visualizer HTML into lib/visualizer-html.ts');
